// hostAliases returns cn plus whichever form it's missing — its shortname
// if cn is already an FQDN, or cn.domain (synthesized) if cn is bare and a
// domain is known — as one space-separated hosts-line name list.
func hostAliases(cn, domain string) string {
	if i := strings.IndexByte(cn, '.'); i >= 0 {
		return cn + " " + cn[:i]
	}
	if domain != "" {
		return cn + "." + domain + " " + cn
	}
	return cn
}

// CertsHostsContent renders certs.hosts: server CN always, plus one line
// per connected, non-revoked, included client CN at its live tun IP.
// A disconnected client has no line — correct, not a limitation.
func CertsHostsContent(certs []store.Cert, live []controller.VPNClient, serverCN string, serverIP net.IP) []byte {
	domain := ovpnconf.Domain(serverCN)

	included := make(map[string]bool, len(certs))
	for _, c := range certs {
		if c.RevokedAt == nil && c.IncludeDNS {
			included[c.CN] = true
		}
	}

	var clientLines []string
	for _, cl := range live {
		if cl.CN == serverCN || cl.VirtualAddress == "" || !included[cl.CN] {
			continue
		}
		clientLines = append(clientLines, fmt.Sprintf("%s %s\n", cl.VirtualAddress, hostAliases(cl.CN, domain)))
	}
	sort.Strings(clientLines) // stable output regardless of mgmt's client order

	var b strings.Builder
	b.WriteString("# generated by ovcp — do not edit; regenerated on every cert change and stats tick\n")
	if serverCN != "" && serverIP != nil && net.ParseIP(serverCN) == nil { // an address CN names no host
		fmt.Fprintf(&b, "%s %s\n", serverIP, hostAliases(serverCN, domain))
	}
	for _, l := range clientLines {
		b.WriteString(l)
	}
	return []byte(b.String())
}

// RecordList is the internal DNS records: every cert with where it resolves
// right now, and custom.hosts' content (record list, GET /api/records).
type RecordList struct {
	Certs  []CertRow `json:"certs"`
	Custom string    `json:"custom"`
}

// Records builds a RecordList. A cert resolves at its CN's live address (the
// server at its tun IP); a revoked one never does, it holds no session.
func Records(certs []store.Cert, live []controller.VPNClient, serverCN string, serverIP net.IP, custom string) RecordList {
	ip := map[string]string{}
	for _, cl := range live {
		if cl.VirtualAddress != "" {
			ip[cl.CN] = cl.VirtualAddress
		}
	}
	if serverIP != nil {
		ip[serverCN] = serverIP.String()
	}
	rows := make([]CertRow, 0, len(certs))
	for _, c := range certs {
		r := NewCertRow(c)
		if c.RevokedAt == nil {
			r.IP = ip[c.CN]
		}
		rows = append(rows, r)
	}
	return RecordList{rows, custom}
}

func (s *Server) handleRecords(c call, _ none) (RecordList, error) {
	certs, err := s.Store.ListCerts()
	if err != nil {
		return RecordList{}, httpError{500, err}
	}
	live, _ := s.Mgmt.Status() // openvpn down: nothing resolves live
	ip, _ := s.LoadConfig().ServerTunIP()
	custom, _ := os.ReadFile(s.CustomHostsPath)
	return Records(certs, live, s.DefaultRemote(), ip, string(custom)), nil
}

// RefreshCertsHosts regenerates certs.hosts from live. RunSampler's ticker
// is the server's only caller — cert issue/revoke/DNS-toggle just wait for
// the next tick; the CLI (no running Server) calls it directly instead.
func (s *Server) RefreshCertsHosts(live []controller.VPNClient) error {
	if s.CertsHostsPath == "" {
		return nil // dnsmasq not configured — nothing to write
	}
	certs, err := s.Store.ListCerts()
	if err != nil {
		return err
	}
	var serverIP net.IP
	if ip, err := s.LoadConfig().ServerTunIP(); err == nil {
		serverIP = ip
	}
	data := CertsHostsContent(certs, live, s.DefaultRemote(), serverIP)
	return WriteAtomicHosts(s.CertsHostsPath, data)
}

// WriteAtomicHosts installs data at path via temp+rename, skipped when data is
// unchanged so dnsmasq's inotify watch fires only on real changes.
func WriteAtomicHosts(path string, data []byte) error {
	if cur, err := os.ReadFile(path); err == nil && bytes.Equal(cur, data) {
		return nil
	}
	tmp := filepath.Join(filepath.Dir(path), "."+filepath.Base(path)+".tmp")
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}
